import type { ActiveServer } from '../../../core/server/registry/activeServerModel';
import { qrSvgMarkup } from '../../../core/xr/headsetQr';

/**
 * #19: what a standalone headset opens to join a scene, and the page that
 * shows it. vscode-free, so it is unit-tested; `headsetQrPanel.ts` shows it.
 *
 * WebXR needs a secure context, so a headset needs an HTTPS address:
 * - the Cloudflare invitation link while the server is shared (a real
 *   certificate, reachable from anywhere; the guest is let in with the
 *   pairing code VS Code shows);
 * - else the local network address of an HTTPS server (same network only;
 *   the headset's browser warns about the self-signed certificate once);
 * - else nothing: a plain HTTP server must be shared first.
 */
export type HeadsetTarget =
    | { readonly kind: 'invitation' | 'lan'; readonly url: string }
    | { readonly kind: 'none' };

export function headsetTarget(server: Pick<ActiveServer, 'certMode' | 'remoteAccess'>, lanUrl: string): HeadsetTarget {
    const invitation = server.remoteAccess?.status === 'shared' ? server.remoteAccess.invitationUrl : undefined;
    if (invitation?.startsWith('https://')) {
        return { kind: 'invitation', url: invitation };
    }
    if (server.certMode !== 'http' && lanUrl.startsWith('https://')) {
        return { kind: 'lan', url: lanUrl };
    }
    return { kind: 'none' };
}

function escapeHtml(text: string): string {
    return text.replace(/[&<>"']/g, (char) => `&#${char.charCodeAt(0)};`);
}

const STEPS: Readonly<Record<'invitation' | 'lan', string>> = {
    invitation: 'On the headset, open the browser and scan this code, or type the link. Enter the pairing code VS Code shows, then press the scene\'s VR button.',
    lan: 'Put the headset on the same network as this computer. Open its browser and scan this code, or type the address, and accept the certificate warning once (the certificate is generated by Code-XR). Then press the scene\'s VR button.',
};

/** The webview's whole page: no script, inline styles only, the QR code as inline SVG. */
export function headsetPageHtml(target: HeadsetTarget, serverLabel: string, cspSource: string): string {
    const body = target.kind === 'none'
        ? `<p>A headset needs an HTTPS address it can reach, and this server is served over plain HTTP.</p>
<p>Start remote access for it (<strong>Start Remote Access</strong> on the server in ACTIVE SERVERS), then open this page again.</p>`
        : `<div class="qr">${qrSvgMarkup(target.url)}</div>
<p>${escapeHtml(STEPS[target.kind])}</p>
<p class="link">${escapeHtml(target.url)}</p>`;
    return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src ${cspSource} 'unsafe-inline';">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Open on a headset</title>
<style>
body { font-family: var(--vscode-font-family); color: var(--vscode-foreground); padding: 16px 24px; max-width: 560px; }
.qr { display: inline-block; padding: 8px; background: #fff; border-radius: 4px; }
.link { font-family: var(--vscode-editor-font-family); word-break: break-all; user-select: text; }
</style>
</head>
<body>
<h2>Open ${escapeHtml(serverLabel)} on a headset</h2>
${body}
</body>
</html>`;
}
